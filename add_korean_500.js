async function main() {
  console.log('한국 전통 속담 및 유래 데이터 가져오는 중...');
  const [mainDataText, uraeHtml] = await Promise.all([
    fetch('https://raw.githubusercontent.com/adjh54ir/3ha-proverb-quiz/main/src/const/ConstMainData.ts').then(r => r.text()),
    fetch('https://raw.githubusercontent.com/noralisadderley410-stack/sokdam-urae/main/index.html').then(r => r.text())
  ]);

  // 1. sokdam-urae 에서 속담 유래 사전 추출
  const uraeMap = new Map();
  const mUrae = uraeHtml.match(/const proverbDB = (\[[\s\S]*?\]);/);
  if (mUrae) {
    const arr = eval(mUrae[1]);
    for (const it of arr) {
      if (it.name && it.origin) {
        uraeMap.set(it.name.trim(), it.origin.trim());
      }
    }
  }
  console.log(`속담 상세 유래 사전 로드: ${uraeMap.size}개`);

  // 2. ConstMainData.ts 에서 PROVERB 배열 추출
  const startIdx = mainDataText.indexOf('PROVERB: [');
  const arrStart = mainDataText.indexOf('[', startIdx);
  const arrEnd = mainDataText.lastIndexOf(']');
  const arrCode = mainDataText.slice(arrStart, arrEnd + 1);
  const proverbs = eval(arrCode);
  console.log(`표준국어대사전 기반 한국 속담 로드: ${proverbs.length}개`);

  const koreanItems = [];
  const seenKo = new Set();

  // A. 한국 역사 위인·사상가·문학가 명언 먼저 추가
  for (const [quoteText, meaningText, authorText, noteText] of KOREAN_GREAT_QUOTES) {
    const key = quoteText.trim();
    if (!seenKo.has(key)) {
      seenKo.add(key);
      koreanItems.push({
        category: '한국명언',
        original: quoteText.trim(),
        korean: meaningText.trim(),
        author: authorText.trim(),
        note: noteText.trim()
      });
    }
  }

  // B. 한국 전통 속담 (유래가 풍부한 것 + 예문·풀이가 좋은 순으로 정렬하여 500개 채우기)
  proverbs.sort((a, b) => {
    const hasUraeA = uraeMap.has(a.proverb) ? 1 : 0;
    const hasUraeB = uraeMap.has(b.proverb) ? 1 : 0;
    if (hasUraeA !== hasUraeB) return hasUraeB - hasUraeA;
    return (b.longMeaning?.length || 0) - (a.longMeaning?.length || 0);
  });

  for (const p of proverbs) {
    if (koreanItems.length >= 500) break;
    const prov = p.proverb.trim();
    if (seenKo.has(prov)) continue;
    seenKo.add(prov);

    const meaning = (p.longMeaning || p.meaning || '').trim();
    const noteParts = [];

    if (uraeMap.has(prov)) {
      noteParts.push(`유래·배경: ${uraeMap.get(prov)}`);
    }
    if (Array.isArray(p.example) && p.example.length > 0) {
      noteParts.push(`예문: ${p.example[0]}`);
    }
    if (Array.isArray(p.sameProverb) && p.sameProverb.length > 0) {
      noteParts.push(`비슷한 속담: ${p.sameProverb.slice(0, 2).join(', ')}`);
    }

    koreanItems.push({
      category: '한국명언',
      original: prov,
      korean: meaning,
      author: `한국 전통 속담 · 《표준국어대사전》 (${p.category || '삶의 지혜'})`,
      note: noteParts.join(' | ') || p.origin || '조상들의 삶의 지혜가 담긴 우리말 속담'
    });
  }

  console.log(`생성된 한국 명언·속담 총 개수: ${koreanItems.length}개`);

  // 기존 quotes_1000.json 에서 영어명언 500개, 한자/사자성어 500개 분리
  const existingPath = path.join(__dirname, 'quotes_1000.json');
  const existing = JSON.parse(fs.readFileSync(existingPath, 'utf8'));
  const enList = existing.filter(x => x.category === '영어명언').slice(0, 500);
  const hjList = existing.filter(x => x.category === '사자성어' || x.category === '한자명언').slice(0, 500);
  const koList = koreanItems.slice(0, 500);

  // 1:1:1 비율로 교차 배치 (1번 영어, 2번 한자/사자성어, 3번 한국명언/속담...) -> 총 1,500개!
  const combined1500 = [];
  for (let i = 0; i < 500; i++) {
    if (enList[i]) {
      combined1500.push({
        ...enList[i],
        id: combined1500.length + 1,
        sent_count: 0,
        last_sent: ''
      });
    }
    if (hjList[i]) {
      combined1500.push({
        ...hjList[i],
        id: combined1500.length + 1,
        sent_count: 0,
        last_sent: ''
      });
    }
    if (koList[i]) {
      combined1500.push({
        ...koList[i],
        id: combined1500.length + 1,
        sent_count: 0,
        last_sent: ''
      });
    }
  }

  console.log(`최종 통합 데이터셋 개수: ${combined1500.length}개 (서양 500 + 동양한자 500 + 한국 500)`);

  fs.writeFileSync(existingPath, JSON.stringify(combined1500, null, 2), 'utf8');

  // CSV 재생성
  const escapeCsv = (val) => {
    const str = String(val ?? '').replace(/\r?\n/g, ' ');
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };
  const headers = ['번호', '구분', '원문_또는_한자', '한국어_번역_뜻풀이', '인물_출전', '상세풀이_비고', '발송횟수', '최근발송일시'];
  const csvLines = [headers.join(',')];
  for (const row of combined1500) {
    csvLines.push([
      row.id,
      escapeCsv(row.category),
      escapeCsv(row.original),
      escapeCsv(row.korean),
      escapeCsv(row.author),
      escapeCsv(row.note),
      row.sent_count,
      escapeCsv(row.last_sent)
    ].join(','));
  }
  fs.writeFileSync(path.join(__dirname, 'quotes_1000.csv'), '\uFEFF' + csvLines.join('\r\n'), 'utf8');

  const compactRows = combined1500.map(r => [r.id, r.category, r.original, r.korean, r.author, r.note, 0, '']);
  fs.writeFileSync(path.join(__dirname, 'QuotesData.gs'), `function getInitialQuotesData_() {\n  return ${JSON.stringify(compactRows)};\n}\n`, 'utf8');
}

main().catch(console.error);
