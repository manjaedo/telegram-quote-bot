const quotesPath = path.join(__dirname, 'quotes_1000.json');
const quotes = JSON.parse(fs.readFileSync(quotesPath, 'utf8'));

// 한국명언 카테고리 아이템들을 찾아서 뒤쪽의 일반 속담 일부를 왕·장군·학자 명언으로 교체하여 균형 맞추기
const koIndices = [];
quotes.forEach((q, idx) => {
  if (q.category === '한국명언') koIndices.push(idx);
});

// 뒤쪽(400번째 이후)의 일반 속담 자리에 MORE_KOREAN_GREATS 를 삽입하여
// 왕·장군·학자·위인 명언(약 100여 개)과 한국 전통 속담(약 400개)이 앞뒤로 골고루 섞이게 구성
let replacePtr = koIndices.length - 1;
for (const [orig, kor, auth, note] of MORE_KOREAN_GREATS) {
  if (replacePtr < 0) break;
  const targetIdx = koIndices[replacePtr];
  quotes[targetIdx] = {
    id: quotes[targetIdx].id,
    category: '한국명언',
    original: orig,
    korean: kor,
    author: auth,
    note: note,
    sent_count: 0,
    last_sent: ''
  };
  replacePtr--;
}

// 한국명언 500개 내부에서 위인(왕·장군·학자) 명언과 전래 속담이 한쪽에 몰리지 않고 골고루 섞이도록 재배치
const allKo = koIndices.map(i => quotes[i]);
const greats = allKo.filter(q => !q.author.startsWith('한국 전통 속담'));
const proverbs = allKo.filter(q => q.author.startsWith('한국 전통 속담'));

const mixedKo = [];
let gIdx = 0;
let pIdx = 0;
while (gIdx < greats.length || pIdx < proverbs.length) {
  if (gIdx < greats.length) mixedKo.push(greats[gIdx++]);
  for (let k = 0; k < 4 && pIdx < proverbs.length; k++) {
    mixedKo.push(proverbs[pIdx++]);
  }
}

koIndices.forEach((qIdx, i) => {
  quotes[qIdx] = {
    ...mixedKo[i],
    id: quotes[qIdx].id
  };
});

fs.writeFileSync(quotesPath, JSON.stringify(quotes, null, 2), 'utf8');
console.log(`한국 왕·장군·대학자·위인 명언: ${greats.length}개, 한국 전래 속담: ${proverbs.length}개로 재구성 완료!`);
